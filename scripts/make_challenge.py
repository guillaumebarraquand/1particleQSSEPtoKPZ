#!/usr/bin/env python3
"""Generate Challenge.lean from the statement files of the library.

Challenge.lean is the single file that states Theorem 1.2 and its companion statements and
imports Mathlib only (the layout checked by the Lean `comparator` tool). It is the
concatenation of the bodies of the files listed in SOURCES, with their Mathlib imports merged
and their imports of project files removed. It is never edited by hand: edit the sources and
run

    python3 scripts/make_challenge.py          # rewrite Challenge.lean
    python3 scripts/make_challenge.py --check  # exit 1 if Challenge.lean is out of date
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
SOURCES = [
    "QSSEPtoKPZ/Definitions.lean",
    "QSSEPtoKPZ/MainTheorem.lean",
    "QSSEPtoKPZ/Companions.lean",
]
TARGET = ROOT / "Challenge.lean"

HEADER = """\
/-
Formal statement of the main theorem of
  G. Barraquand, "Convergence of the one-particle quantum symmetric simple exclusion process
  to the KPZ equation" (2026).
Lean 4 / Mathlib formalization written by Claude (Anthropic) at the request of the author,
November 2026. See README.md.

Challenge file: the definitions, Theorem 1.2 and its companion statements, importing Mathlib
only. GENERATED by scripts/make_challenge.py from
{sources}.
Do not edit by hand.
-/
module

"""


def split(path: str) -> tuple[list[str], str]:
    """Return the Mathlib imports of a source file and its body (what follows the imports)."""
    lines = (ROOT / path).read_text().splitlines(keepends=True)
    last_import = max(i for i, l in enumerate(lines) if l.startswith("public import "))
    imports = []
    for l in lines[: last_import + 1]:
        if l.startswith("public import "):
            module = l.split()[2]
            if module.startswith("Mathlib"):
                imports.append(module)
            elif not module.startswith("QSSEPtoKPZ"):
                sys.exit(f"{path}: import of {module}, neither Mathlib nor the project")
    return imports, "".join(lines[last_import + 1 :]).strip("\n") + "\n"


def generate() -> str:
    imports: list[str] = []
    bodies = []
    for path in SOURCES:
        imp, body = split(path)
        imports += [m for m in imp if m not in imports]
        bodies.append(f"/- ===== From {path} ===== -/\n\n{body}")
    sources = ",\n".join(f"  {p}" for p in SOURCES)
    return (
        HEADER.format(sources=sources)
        + "".join(f"public import {m}\n" for m in sorted(imports))
        + "\n"
        + "\n".join(bodies)
    )


def main() -> None:
    text = generate()
    if "--check" in sys.argv[1:]:
        if not TARGET.exists() or TARGET.read_text() != text:
            sys.exit("Challenge.lean is out of date: run python3 scripts/make_challenge.py")
        print("Challenge.lean is up to date.")
    else:
        TARGET.write_text(text)
        print(f"Wrote {TARGET.name} ({text.count(chr(10))} lines).")


if __name__ == "__main__":
    main()
